#!/usr/bin/env python3
"""Record-based verification statuses (POLICY 11, ROADMAP 4.5).

`ledger/verification_record.json` is the master: one entry per claim with its record status (`corroborated`,
`disputed`, `contradicted-by-record`), the evidence (source id, location, kind, speaker, verbatim quote) and a note.
This script syncs those statuses into the episode JSON (`Verification:` and `Verification Evidence:` with the S-ids)
and renders `ledger/verification_record.md` for review. A claim the host herself revised keeps `revised-by-host`
(the record entry stays in the ledger). A record status whose ledger entry is gone is removed. Run
`derive_status.py` afterwards to copy statuses into the inscriptions (finalize does both).

Usage (from agent-lab root):
  python3 projects/monuments/cka/scripts/verification/apply_record.py [--add FILE]
  (--add: JSON list of entries to add or replace in the master, keyed by claim id)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

CKA = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CKA / "scripts" / "source"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cka_source as cs  # noqa: E402
from derive_status import set_line  # noqa: E402

RECORD = ("corroborated", "disputed", "contradicted-by-record")
LEDGER = CKA / "ledger" / "verification_record.json"


def sid_key(s: str) -> tuple:
    return tuple(int(x) for x in re.findall(r"\d+", s))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--add", type=Path)
    a = ap.parse_args()
    master = {e["claim"]: e for e in json.loads(LEDGER.read_text(encoding="utf-8"))} if LEDGER.exists() else {}
    if a.add:
        for e in json.loads(a.add.read_text(encoding="utf-8")):
            if e["status"] not in RECORD or not e.get("evidence"):
                sys.exit(f"bad entry {e.get('claim')}: status {e.get('status')!r}, {len(e.get('evidence') or [])} evidence")
            master[e["claim"]] = e
    sources = {s["id"]: s for s in json.loads((CKA / "sources" / "manifest.json").read_text(encoding="utf-8"))["sources"]}
    man = {e["seq"]: e for e in json.loads((CKA / "input" / "episode_manifest.json").read_text(encoding="utf-8"))["episodes"]}
    counts, kept_host, dirty = Counter(), [], set()
    seen = set()
    for seq in sorted(man):
        if not cs.src_path(seq).exists():
            continue
        doc = cs.load(seq)
        changed = False
        for it in cs.items(doc, "claim"):
            cid, cur = it["id"], cs.field(it, "Verification")
            e = master.get(cid)
            if e:
                seen.add(cid)
                e.update({"episode": seq, "claim_text": cs.field(it, "Claim") or ""})
                if cur == "revised-by-host":
                    kept_host.append(cid)
                    continue
                sids = ", ".join(sorted({x["sid"] for x in e["evidence"]}, key=sid_key))
                changed |= set_line(it, "Verification", e["status"]) | set_line(it, "Verification Evidence", sids)
                counts[e["status"]] += 1
            elif cur in RECORD:
                changed |= set_line(it, "Verification", None) | set_line(it, "Verification Evidence", None)
        if changed:
            cs.save(doc)
            dirty.add(seq)
    missing = sorted(set(master) - seen, key=sid_key)
    if missing:
        sys.exit(f"ledger claims not in the archive: {', '.join(missing[:10])}")
    out = sorted(master.values(), key=lambda e: sid_key(e["claim"]))
    LEDGER.parent.mkdir(exist_ok=True)
    LEDGER.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    md = ["# Verification against the record (ROADMAP 4.5)", "",
          f"{len(out)} claims checked against Tier 1 records and Tier 2 reporting (POLICY 11): "
          + ", ".join(f"{n} {s}" for s, n in sorted(Counter(e['status'] for e in out).items()))
          + f". {len(kept_host)} of them keep `revised-by-host` because the host later revised them. Each entry cites "
          "the record with a verbatim quote and its location. Generated by `scripts/verification/apply_record.py` "
          "from `verification_record.json`.", "", "Sources:", ""]
    md += [f"- **{s}**: {sources[s]['title']} ({sources[s]['date']}, {sources[s]['publisher']})"
           for s in sorted({x['sid'] for e in out for x in e['evidence']}, key=sid_key)]
    md.append("")
    for st in ("contradicted-by-record", "disputed", "corroborated"):
        group = [e for e in out if e["status"] == st]
        if not group:
            continue
        md += [f"## {st} ({len(group)})", ""]
        for e in group:
            md.append(f"### {e['claim']} (ep {e['episode']}){' · keeps revised-by-host' if e['claim'] in kept_host else ''}")
            md.append(f"- **Claim:** {e['claim_text']}")
            md.append(f"- **Record:** {e['note']}")
            for x in e["evidence"]:
                md.append(f"  - {x['sid']} {x['loc']} ({x['kind']}, {x['speaker']}): \"{x['quote']}\"")
            md.append("")
    (CKA / "ledger" / "verification_record.md").write_text("\n".join(md), encoding="utf-8")
    print(f"record statuses: {dict(sorted(counts.items()))}; kept revised-by-host: {len(kept_host)}; "
          f"episodes rewritten: {len(dirty)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
