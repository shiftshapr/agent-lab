#!/usr/bin/env python3
"""Then-vs-now ledger export (ROADMAP 5.3).

Collects every Revises, Contradicts and Qualifies link between claims (newer claim -> older claim) from the JSON
source, with both clips (episode, date, timestamp, YouTube link at that second), both claim texts and snippets, and
the delta. `ledger/then_vs_now.json` is the master. On re-export it keeps each pair's `delta`, `review` status
(unreviewed | approved | rejected | hold) and `note`, adds new pairs and drops pairs whose link is gone.
`ledger/then_vs_now.md` is rendered from it for review: host-vs-herself pairs first, by relation, newest first.

Usage (from agent-lab root):
  python3 projects/monuments/cka/scripts/ledger/export_then_vs_now.py [--deltas FILE]
  (--deltas: JSON list of {"later", "earlier", "delta"} to fill in deltas for new pairs)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

CKA = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CKA / "scripts" / "source"))
import cka_source as cs  # noqa: E402

OTHER_VOICE = re.compile(r"\b(?:clip|reads|per the|according to|quotes?|comment|post|article|document|email|text message|tweet)\b", re.I)
KEYS = {"Revises": "revises", "Contradicts": "contradicts", "Qualifies": "qualifies"}


def secs(ts: str | None) -> int:
    m = re.match(r"(\d+):(\d+):(\d+)", ts or "")
    return int(m.group(1)) * 3600 + int(m.group(2)) * 60 + int(m.group(3)) if m else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--deltas", type=Path)
    a = ap.parse_args()
    man = {e["seq"]: e for e in json.loads((CKA / "input" / "episode_manifest.json").read_text(encoding="utf-8"))["episodes"]}
    claims, links = {}, []
    for seq in sorted(man):
        if not cs.src_path(seq).exists():
            continue
        for it in cs.items(cs.load(seq), "claim"):
            text = cs.field(it, "Claim") or ""
            claims[it["id"]] = {"id": it["id"], "episode": seq, "candace_ep": man[seq].get("candace_ep_number"),
                                "date": man[seq]["upload_date"], "timestamp": cs.field(it, "Claim Timestamp"),
                                "clip": f"https://youtu.be/{man[seq]['youtube_id']}?t={secs(cs.field(it, 'Claim Timestamp'))}",
                                "claim": text, "snippet": cs.field(it, "Transcript Snippet") or "",
                                "host_voice": text.startswith("The host ") and not OTHER_VOICE.search(text)}
            for key, rel in KEYS.items():
                for old in re.findall(r"C-\d+", cs.field(it, key) or ""):
                    links.append((it["id"], old, rel))
    lp = CKA / "ledger" / "then_vs_now.json"
    prev = {(p["later"]["id"], p["earlier"]["id"], p["relation"]): p for p in json.loads(lp.read_text(encoding="utf-8"))} if lp.exists() else {}
    deltas = {(d["later"], d["earlier"]): d.get("delta", "") for d in json.loads(a.deltas.read_text(encoding="utf-8"))} if a.deltas else {}
    out = []
    for later, earlier, rel in links:
        if later not in claims or earlier not in claims:
            continue
        old = prev.get((later, earlier, rel), {})
        out.append({"later": claims[later], "earlier": claims[earlier], "relation": rel,
                    "host_vs_herself": claims[later]["host_voice"] and claims[earlier]["host_voice"],
                    "delta": old.get("delta") or deltas.get((later, earlier), ""),
                    "review": old.get("review", "unreviewed"), "note": old.get("note", "")})
    order = {"revises": 0, "contradicts": 1, "qualifies": 2}
    out.sort(key=lambda p: (not p["host_vs_herself"], order[p["relation"]], p["later"]["date"]), reverse=False)
    lp.parent.mkdir(exist_ok=True)
    lp.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    md = ["# Then vs. now ledger (ROADMAP 5.3)", "",
          f"{len(out)} links: {sum(p['host_vs_herself'] for p in out)} are the host against herself. Each lists the "
          "newer claim, the older one it revises, contradicts or qualifies, both clips and the delta. `review` is set by "
          "Daveed in `then_vs_now.json` (approved, rejected or hold). Generated by `scripts/ledger/export_then_vs_now.py`.", ""]
    for p in out:
        L, E = p["later"], p["earlier"]
        md += [f"## {p['relation']}: {L['id']} ({L['date']}) → {E['id']} ({E['date']}){'' if p['host_vs_herself'] else ' · not host vs herself'} · review: {p['review']}",
               f"- **Delta:** {p['delta'] or '(none recorded)'}",
               f"- **Then** (ep {E['episode']}, Candace Ep {E['candace_ep']}, {E['timestamp']}, [clip]({E['clip']})): {E['claim']}",
               f"- **Now** (ep {L['episode']}, Candace Ep {L['candace_ep']}, {L['timestamp']}, [clip]({L['clip']})): {L['claim']}", ""]
    (CKA / "ledger" / "then_vs_now.md").write_text("\n".join(md), encoding="utf-8")
    print(f"{len(out)} links ({sum(p['host_vs_herself'] for p in out)} host vs herself) -> ledger/then_vs_now.json, .md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
